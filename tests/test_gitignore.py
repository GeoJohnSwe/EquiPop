# -*- coding: utf-8 -*-
"""The repository's ignore rules, kept by a test (review of 1.63.2, M1).

The rules below were added in earlier releases - BACKLOG 350 after a
release shipped a stale second copy of the package from `build/` - but
they lived in the release trees and never reached the repository. The
1.63.2 tree was rebuilt from a clone, so it carried the four-line
.gitignore the repository had always held, and nothing noticed: the
packaging tests check what goes INTO a release archive, not what the
working tree is protected against committing.
"""
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]

REQUIRED = [
    "__pycache__/",
    "*.pyc",
    "dist/",
    ".pytest_cache/",
    "build/",            # BACKLOG 350
    "*.egg-info/",       # BACKLOG 350
    ".mypy_cache/",
    ".ruff_cache/",
    "arcgis/*.pyt.xml",  # generated by arcgis/make_help_xml.py
]


def _rules():
    text = (ROOT / ".gitignore").read_text(encoding="utf-8")
    return {ln.strip() for ln in text.splitlines()
            if ln.strip() and not ln.strip().startswith("#")}


@pytest.mark.parametrize("rule", REQUIRED)
def test_the_ignore_rule_is_present(rule):
    """BROKEN WITH: the 1.63.2 .gitignore (the first four lines only)."""
    assert rule in _rules(), f".gitignore has lost {rule!r}"


def test_nothing_the_package_needs_is_ignored():
    """An ignore rule that matched shipped files would hide them from
    git. None of the rules may match a file the release builds from."""
    rules = _rules()
    for shipped in ("pyproject.toml", "equipop/__init__.py",
                    "stata/equipop.ado", "arcgis/EquiPop.pyt",
                    "arcgis/make_help_xml.py"):
        p = Path(shipped)
        for rule in rules:
            assert not p.match(rule.rstrip("/")), (shipped, rule)
