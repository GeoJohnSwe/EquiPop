#!/usr/bin/env python3
# =====================================================================
# make_release_zip.py - build the complete source ZIP, safely.
#
# BACKLOG 156. The 1.29.6 release ZIP could not be extracted on
# Windows. Five of its members were named
#
#     EquiPop-1.29.6/C:\Data\...\gridby_points_EquiPop_run.csv
#
# because the test suite writes run manifests into the working
# directory (BACKLOG 101) and the zip was built from the whole tree.
# Windows refuses drive-letter syntax inside an archive member, so the
# file needed deliberate member-skipping to open at all.
#
# The clean-up HAD been run - before the test suite, which then
# recreated the files. That is the lesson: a manual step in the right
# order is not a fix, because the order will be got wrong again. So
# the check lives here, runs every time, and REFUSES rather than
# warns.
#
# Usage:  python tools/make_release_zip.py <version> [outdir]
# =====================================================================

import os
import re
import sys
import zipfile

# Anything matching these cannot be extracted reliably, or should
# never have been in the tree in the first place.
BAD_NAME = re.compile(
    r"""(^[A-Za-z]:)      # a drive letter: C:\...
      | \\                # a backslash anywhere
      | (^/)              # an absolute path
      | (^|/)\.\.(/|$)    # a traversal component
      | [:*?"<>|]         # characters Windows refuses in a name
    """, re.VERBOSE)

SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", "node_modules",
             "equipop.egg-info", ".mypy_cache", ".ruff_cache",
             # BACKLOG 350, v1.51.1. `python -m build` leaves these,
             # and the release zip swept them in - so the archive John
             # unzips over his working tree and COMMITS carried a
             # second, frozen copy of the whole package.
             # 1.51.0 SHIPPED THAT: `build/lib/equipop/` held all 40
             # modules, stale at whatever version last built, and
             # nothing noticed because the file names are all valid
             # and the zip extracts perfectly. A grep of the tree
             # would then find every rule twice, which is this
             # project's signature defect arriving through the
             # directory layout rather than through the code.
             # `dist/` is the same mistake 3 MB larger: the wheel and
             # the source archive are SIBLINGS of this zip in the
             # release bundle, so a copy inside it is pure
             # duplication.
             # In the tool, not in a checklist, for the reason the
             # docstring above already gives.
             "build", "dist"}
SKIP_SUFFIX = (".pyc", ".pyo")

# BACKLOG 404, v1.54.6. BUILD OUTPUTS THAT ARE NOT SKIPPABLE.
# EquiPop.<Tool>.pyt.xml are generated by arcgis/make_help_xml.py.
# MANIFEST.in ships them in the sdist and the bundle ships them loose;
# the WORKING TREE must not carry them (BACKLOG 45), and
# test_the_sidecars_are_not_committed_to_the_repository asserts that.
# So a release zip built while they are lying in arcgis/ hands John an
# archive he unzips over his tree, commits, and whose own suite then
# fails on his machine. 1.54.0 shipped exactly that and it was caught
# by hand.
# WHY REFUSE AND NOT SKIP, which is this file's standing rule: a skip
# would build a clean zip and leave the files behind, so the next
# `pytest` fails instead - the fault moved, not removed. And the build
# ORDER is the trap, exactly as the docstring above says: the bundle's
# own Pro step needs these files present, so they are generated,
# built from, and then deleted. A step whose order matters belongs in
# a tool and not in a memory.
BUILD_OUTPUT_SUFFIX = (".pyt.xml",)


def members(root):
    """Every file that should ship, as (absolute path, archive name)."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if fn.endswith(SKIP_SUFFIX):
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            yield full, rel


def check(names):
    """Refuse the whole build if any name cannot be extracted."""
    bad = [n for n in names if BAD_NAME.search(n)]
    if bad:
        raise SystemExit(
            "\n  REFUSING to build the release ZIP: "
            f"{len(bad)} member name(s) cannot be extracted on Windows.\n\n"
            + "".join(f"      {n}\n" for n in bad[:10])
            + ("      ...\n" if len(bad) > 10 else "")
            + "\n  These are almost certainly run manifests written into\n"
              "  the working directory by the test suite (BACKLOG 101).\n"
              "  Delete them and build again - do not skip them, or the\n"
              "  next release will carry them too.\n")


def check_build_outputs(names):
    """Refuse the whole build if a generated file is in the tree."""
    bad = [n for n in names if n.endswith(BUILD_OUTPUT_SUFFIX)]
    if bad:
        raise SystemExit(
            "\n  REFUSING to build the release ZIP: "
            f"{len(bad)} generated file(s) are sitting in the tree.\n\n"
            + "".join(f"      {n}\n" for n in bad[:10])
            + ("      ...\n" if len(bad) > 10 else "")
            + "\n  These are ArcGIS Pro help sidecars, written by\n"
              "  arcgis/make_help_xml.py. They SHIP - in the sdist and\n"
              "  loose in the release bundle - but they must not be in\n"
              "  the working tree (BACKLOG 45), and the test suite\n"
              "  asserts that. A zip carrying them is one John unzips\n"
              "  over his tree, commits, and whose own suite then\n"
              "  fails on his machine.\n\n"
              "  Delete them and build again:\n"
              "      rm arcgis/*.pyt.xml\n"
              "  They are regenerated by make_help_xml.py whenever the\n"
              "  Pro bundle needs them, so nothing is lost.\n")


def build(root, version, outdir):
    top = f"EquiPop-{version}"
    out = os.path.join(outdir, f"{top}-complete.zip")
    found = list(members(root))
    check([rel for _, rel in found])
    check_build_outputs([rel for _, rel in found])
    os.makedirs(outdir, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for full, rel in sorted(found, key=lambda t: t[1]):
            z.write(full, f"{top}/{rel}")
    return out, len(found)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: make_release_zip.py <version> [outdir]")
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path, n = build(here, sys.argv[1],
                    sys.argv[2] if len(sys.argv) > 2 else here)
    print(f"  wrote {path}  ({n:,} files, every name checked)")
